# 辅助函数
# ============================================================

def get_agent_prompt(agent_name: str) -> str:
    """
    获取指定Agent的系统提示词

    Args:
        agent_name: Agent名称 (supervisor/collector/analyzer/writer)

    Returns:
        对应的系统提示词
    """
    prompts = {
        "supervisor": SUPERVISOR_SYSTEM_PROMPT,
        "collector": COLLECTOR_SYSTEM_PROMPT,
        "analyzer": ANALYZER_SYSTEM_PROMPT,
        "writer": WRITER_SYSTEM_PROMPT,
    }
    return prompts.get(agent_name.lower(), "")


def format_task_message(task_type: str, **kwargs) -> str:
    """
    格式化任务消息

    Args:
        task_type: 任务类型 (collector/analyzer/writer)
        **kwargs: 各任务类型的参数

    Returns:
        格式化的任务消息
    """
    if task_type == "collector":
        return COLLECTOR_TASK_TEMPLATE.format(**kwargs)
    elif task_type == "analyzer":
        return ANALYZER_TASK_TEMPLATE.format(**kwargs)
    elif task_type == "writer":
        return WRITER_TASK_TEMPLATE.format(**kwargs)
    return ""
